const { BETA_CALLOUT, PLATFORMS, REACT_NATIVE_DOCS } = require('./config')
const { fencedCode } = require('./sidecar')
const { fail } = require('./errors')

// Pages are lists of blocks joined by a blank line. Optional blocks are
// falsy and dropped. Examples is never dropped for being empty: the build fails
// instead, see the section helper below.
const joinBlocks = (blocks) => `${blocks.filter(Boolean).join('\n\n')}\n`
const section = (title, body) => `## ${title}\n\n${body}`

// Backslashes first, then pipes, so a pipe cannot end the cell early.
const escapeCell = (text) => text.replace(/\\/g, '\\\\').replace(/\|/g, '\\|')

function renderPropsTable(props) {
  const rows = props.map((p) => {
    const type = escapeCell(p.type)
    const description = escapeCell(
      p.optional ? p.description : `${p.description} Required.`,
    )
    const fallback = p.default ? `\`${escapeCell(p.default)}\`` : 'None'
    return `| \`${p.name}\` | \`${type}\` | ${fallback} | ${description} |`
  })
  return [
    '| Prop | Type | Default | Description |',
    '|---|---|---|---|',
    ...rows,
  ].join('\n')
}

// Props that come from a React Native type are not listed in the table, so a
// line under it names the type, linked to its React Native docs.
// A type that left some props out with Omit says which, so the line does not
// claim more than the component takes. A prop that was left out only to be
// declared again, such as Input's `onChange`, is in the table, so it is not
// named as missing.
const listWithAnd = (items) =>
  items.length > 1
    ? `${items.slice(0, -1).join(', ')} and ${items[items.length - 1]}`
    : items[0]

function alsoAccepts(bases = [], props = []) {
  if (!bases.length) return undefined
  const links = bases.map(({ name }) =>
    REACT_NATIVE_DOCS[name]
      ? `[\`${name}\`](https://reactnative.dev/docs/${REACT_NATIVE_DOCS[name]}#props)`
      : `\`${name}\``,
  )
  const listed = new Set(props.map((prop) => prop.name))
  const omitted = [...new Set(bases.flatMap((base) => base.omitted))].filter(
    (key) => !listed.has(key),
  )
  const except = omitted.length
    ? `, except ${listWithAnd(omitted.map((key) => `\`${key}\``))}`
    : ''
  return `Also accepts all React Native ${listWithAnd(links)}${except}.`
}

// One Links row. `urls` is in display order, `indent` is for nesting.
function renderLinks(urls, indent = '') {
  const attrs = Object.entries(urls)
    .filter(([, value]) => value)
    .map(([name, value]) => `${indent}  ${name}="${value}"`)
    .join('\n')
  return `${indent}<Links\n${attrs}\n${indent}/>`
}

function generatedNote(component, relDir) {
  return `{/* Generated by scripts/generate-component-docs.js. Do not edit. Edit ${relDir}/${component}.docs.md, the ${component}Props type or ${component}.stories.tsx instead. */}`
}

// Sections both platforms share. Features is hand-written: a few short lines
// on what the component does for you, which the props cannot show.
const featuresSection = (ctx) => section('Features', ctx.sidecar.Features)

function usageSection(component, platform, ctx) {
  const p = PLATFORMS[platform]
  return section(
    'Usage',
    `\`\`\`bash\n${p.installLine}\n\`\`\`\n\n\`\`\`tsx\n${p.importLine(component)}\n\n${fencedCode(ctx.sidecar.Usage)}\n\`\`\``,
  )
}

// Every example needs a caption, so a reader knows what they are looking at.
// Checked here, on the story objects, before they are mapped to markdown and
// the caption field is lost.
function assertCaptioned(component, stories) {
  const missing = stories.filter((s) => !s.caption).map((s) => s.name)
  if (missing.length) {
    fail(
      `${component}: add a caption to ${missing.map((n) => `\`${n}\``).join(', ')} with parameters.docs.description.story.`,
    )
  }
}

function examplesSection(component, platform, examples) {
  if (!examples.length) {
    fail(
      `${component}: no Examples. ${component}.stories.tsx exports none${platform === 'web' ? '. On web, the Introduction and Overview stories are not examples.' : '.'}`,
    )
  }
  return section('Examples', examples.join('\n\n'))
}

const closingSections = (ctx) => [
  section('Accessibility', ctx.sidecar.Accessibility),
  ctx.sidecar['Related components'] &&
    section('Related components', ctx.sidecar['Related components']),
]

// The React Native tab: plain markdown, no live demos.
function renderMobile(component, ctx) {
  const missing = ctx.stories.find((s) => s.code === undefined)
  if (missing) {
    fail(
      `${component}: no code to show for the example ${missing.name}. On mobile, write each example as a function that returns JSX, or an object with a render function.`,
    )
  }
  assertCaptioned(component, ctx.stories)
  const examples = ctx.stories.map((s) =>
    [s.title && `### ${s.title}`, s.caption, `\`\`\`tsx\n${s.code}\n\`\`\``]
      .filter(Boolean)
      .join('\n\n'),
  )
  return joinBlocks([
    generatedNote(component, ctx.relDir),
    featuresSection(ctx),
    usageSection(component, 'mobile', ctx),
    section(
      'Props',
      [
        ctx.props.length
          ? renderPropsTable(ctx.props)
          : `${component} has no props of its own.`,
        alsoAccepts(ctx.baseTypes, ctx.props),
        ...(ctx.subComponents ?? []).map((sub) =>
          [
            `### ${sub.name}`,
            sub.props.length
              ? renderPropsTable(sub.props)
              : `${sub.name} has no props of its own.`,
            alsoAccepts(sub.baseTypes, sub.props),
          ]
            .filter(Boolean)
            .join('\n\n'),
        ),
      ]
        .filter(Boolean)
        .join('\n\n'),
    ),
    examplesSection(component, 'mobile', examples),
    ...closingSections(ctx),
  ])
}

// The web story shown right after Features, with no heading and no caption.
const OVERVIEW_STORY = 'Overview'

// The Storybook page: the web docs, with the React Native tab when a mobile
// sidecar exists.
function renderWeb(component, ctx) {
  const p = PLATFORMS.web
  const links = renderLinks({
    figmaUrl: ctx.figmaUrl,
    documentationUrl: ctx.docsUrl,
    ariaUrl: ctx.ariaUrl,
    sourceUrl: ctx.sourceUrl,
    npmUrl: p.npmUrl,
  })
  // The Overview story is the display right after Features. It is not an example.
  const overview = ctx.stories.find((s) => s.name === OVERVIEW_STORY)
  if (!overview) {
    fail(
      `${component}: add an ${OVERVIEW_STORY} story to ${component}.stories.tsx. It is the display shown right after Features.`,
    )
  }
  const exampleStories = ctx.stories.filter((s) => s !== overview)
  assertCaptioned(component, exampleStories)
  const examples = exampleStories.map((s) =>
    [`### ${s.title}`, s.caption, `<Canvas of={Stories.${s.name}} />`]
      .filter(Boolean)
      .join('\n\n'),
  )
  const storybookImports = [
    "import { Meta, Primary, Controls, Canvas } from '@storybook/addon-docs/blocks'",
    `import * as Stories from './${component}.stories'`,
    ctx.hasMobile
      ? "import { Links, PlatformTabs } from './../../../../.storybook/components'"
      : "import { Links } from './../../../../.storybook/components'",
    ctx.hasMobile &&
      `import MobileDocs from '@equinor/eds-mobile-components/docs/${component}.mdx'`,
  ]
  const mobileLinks = renderLinks(
    {
      figmaUrl: ctx.figmaUrl,
      documentationUrl: ctx.docsUrl,
      sourceUrl: ctx.mobileSourceUrl,
      npmUrl: PLATFORMS.mobile.npmUrl,
    },
    '  ',
  )
  return joinBlocks([
    generatedNote(component, ctx.relDir),
    storybookImports.filter(Boolean).join('\n'),
    '<Meta of={Stories} />',
    `# ${component}`,
    ctx.sidecar.Summary,
    BETA_CALLOUT,
    ctx.hasMobile &&
      `<PlatformTabs mobile={<>\n${mobileLinks}\n  <MobileDocs />\n</>}>`,
    links,
    featuresSection(ctx),
    `<Canvas of={Stories.${overview.name}} />`,
    usageSection(component, 'web', ctx),
    section(
      'Props and playground',
      [
        '<Primary />\n<Controls />',
        ...(ctx.subComponents ?? [])
          .filter((sub) => sub.props.length)
          .map((sub) => `### ${sub.name}\n\n${renderPropsTable(sub.props)}`),
      ].join('\n\n'),
    ),
    examplesSection(component, 'web', examples),
    ...closingSections(ctx),
    ctx.hasMobile && '</PlatformTabs>',
  ])
}

module.exports = {
  renderPropsTable,
  renderLinks,
  renderWeb,
  renderMobile,
}
